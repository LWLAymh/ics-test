import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const schema = await readFile(new URL('../../supabase/ics_community_papers.sql', import.meta.url), 'utf8');
const visitor = '11111111-1111-4111-8111-111111111111', other = '22222222-2222-4222-8222-222222222222';
const id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', q = 'q-0123456789abcdef';
test('real PostgreSQL: public publication, deduplication, RLS, moderation, quotas and safe reinstall', async () => {
  const db = new PGlite();
  try {
    await db.exec("create role anon; create role authenticated; create role service_role; create schema auth; create function auth.role() returns text language sql as $$ select current_setting('request.jwt.claim.role', true) $$; grant usage on schema auth to public;");
    await db.exec(schema);
    const token = (await db.query('select token from private.ics_community_publish_key')).rows[0].token;
    await db.exec('set role anon');
    const publish = (paperId = id, owner = visitor, questions = [q]) => db.query('select public.publish_ics_community_paper($1,$2,$3,$4,$5,$6,$7) as id', [paperId, '测试卷', '署名', '描述', questions, owner, token]);
    const listed = () => db.query("select * from public.list_ics_community_papers('newest',0,$1)", [visitor]);
    await publish(); await publish();
    assert.equal((await listed()).rows.length, 1, 'retry is idempotent');
    await assert.rejects(() => publish(id, other), /conflict/);
    await assert.rejects(() => publish(crypto.randomUUID(), visitor, [q, q]), /invalid question/);
    await assert.rejects(() => publish(crypto.randomUUID(), visitor, ['bad-id']), /invalid question/);
    await assert.rejects(() => db.query('select public.publish_ics_community_paper($1,$2,$3,$4,$5,$6,$7)', [crypto.randomUUID(),'x','x','',[q],visitor,null]), /capability required/);
    await assert.rejects(() => db.query('select public.publish_ics_community_paper($1,$2,$3,$4,$5,$6,$7)', [crypto.randomUUID(),'x','x','',[q],visitor,'f'.repeat(64)]), /capability required/);
    await assert.rejects(() => db.query('select token from private.ics_community_publish_key'), /permission denied/);
    await assert.rejects(() => db.query("insert into public.ics_community_papers(id,title,author_name,question_ids) values ($1,'evil','x',$2)", [crypto.randomUUID(), [q]]), /permission denied/);
    await assert.rejects(() => db.query('select * from private.ics_community_likes'), /permission denied/);
    await assert.rejects(() => db.query('select public.moderate_ics_community_paper($1,true)', [id]), /permission denied/);
    await assert.rejects(() => db.query('update public.ics_community_papers set like_count=999'), /permission denied/);
    for (let i = 0; i < 3; i++) await db.query('select public.like_ics_community_paper($1,$2,true)', [id, visitor]);
    let row = (await listed()).rows[0]; assert.equal(Number(row.like_count), 1); assert.equal(row.liked, true);
    for (let i = 0; i < 2; i++) await db.query('select public.like_ics_community_paper($1,$2,false)', [id, visitor]);
    assert.equal(Number((await listed()).rows[0].like_count), 0);
    await Promise.all(Array.from({ length: 3 }, () => db.query('select public.participate_ics_community_paper($1,$2)', [id, visitor])));
    await db.query('select public.participate_ics_community_paper($1,$2)', [id, other]);
    assert.equal(Number((await listed()).rows[0].participant_count), 2);
    for (const message of ['', '修订说明']) await db.query('select public.report_ics_community_paper($1,$2,$3)', [id, visitor, message]);
    const reports = (await db.query('select * from public.ics_community_paper_reports')).rows;
    assert.equal(reports.length, 1); assert.equal(reports[0].message, '修订说明'); assert.ok(!JSON.stringify(reports).includes(visitor));
    await assert.rejects(() => db.query('select public.report_ics_community_paper($1,$2,$3)', [id, visitor, 'x'.repeat(1001)]), /invalid report/);
    for (let i = 0; i < 4; i++) await publish(crypto.randomUUID());
    await assert.rejects(() => publish(crypto.randomUUID()), /publish limit/);
    await db.exec("reset role; set role service_role; select set_config('request.jwt.claim.role','service_role',false)");
    assert.equal((await db.query('select public.moderate_ics_community_paper($1,true) as changed', [id])).rows[0].changed, true);
    await db.exec("reset role; select set_config('request.jwt.claim.role','anon',false); set role anon");
    assert.ok(!(await listed()).rows.some(p => p.id === id));
    assert.equal((await db.query('select * from public.ics_community_papers where id=$1', [id])).rows.length, 0);
    assert.equal((await db.query('select * from public.ics_community_paper_reports')).rows.length, 0);
    await assert.rejects(() => db.query('select public.like_ics_community_paper($1,$2,true)', [id, visitor]), /not available/);
    await assert.rejects(() => publish(), /not available/);
    await db.exec('reset role'); await db.exec(schema);
    assert.equal((await db.query('select token from private.ics_community_publish_key')).rows[0].token, token, 'reinstall preserves narrow publisher token');
    assert.equal((await db.query('select * from public.ics_community_papers')).rows.length, 5, 'reinstall retains papers and receipts');
    await db.query("update public.ics_community_papers set status='published' where id=$1", [id]);
    await db.exec("set role service_role; select set_config('request.jwt.claim.role','service_role',false)");
    await db.query('select public.resolve_ics_community_paper_reports($1)', [id]);
    await db.exec('reset role'); assert.equal((await db.query('select * from private.ics_community_reports')).rows.length, 0);
    await db.query('update private.ics_community_rate set requests=60,window_start=now() where visitor_id=$1', [visitor]);
    await db.exec('set role anon');
    await assert.rejects(() => db.query('select public.like_ics_community_paper($1,$2,true)', [id, visitor]), /rate limit/);
  } finally { await db.close(); }
});
